import assert from 'node:assert/strict';
import {dataSchema,emptyData,invoiceTotals,calculations,conflict,rollForward,nextDay} from '../model.ts';
const d=emptyData();
assert.equal(dataSchema.safeParse(d).success,true);
const task={id:'1',title:'Build',projectId:'',deadline:'2026-10-01',day:'2026-10-03',time:'09:30',minutes:45,done:false,priority:true,repeat:'none'};
d.tasks.push(task);
assert.equal(dataSchema.safeParse(d).success,true);
assert.match(conflict(d,{id:'2',day:'2026-10-03',time:'10:00',minutes:30}),/overlaps/);
assert.equal(conflict(d,{id:'2',day:'2026-10-03',time:'10:15',minutes:15}),'');
assert.match(conflict(d,{id:'2',day:'2026-10-03',time:'23:45',minutes:30}),/midnight/);
assert.equal(rollForward(d,'2026-10-04').tasks[0].time,'');
assert.equal(rollForward(d,'2026-10-04').tasks[0].deadline,'2026-10-01');
assert.equal(nextDay('2026-01-31','monthly'),'2026-02-28');
assert.equal(nextDay('2026-12-31','daily'),'2027-01-01');
assert.equal(invoiceTotals({items:[{qty:7.5,rate:65,description:'Labour'}],taxRate:13,expenses:[{merchant:'Hardware',total:48.60}]}).total,599.48);
const result=calculations('hours = 7.5\nrate = 65\nlabour = hours × rate\n3/4 in to mm\n$10.50\n$20\nsum\n125 × 4 =\nbad = globalThis');
assert.deepEqual(result.map(x=>x.value),['7.5','65','487.5','19.05 mm','30.5','500','Check expression']);
assert.equal(dataSchema.safeParse({...d,tasks:[{...task,time:'10:10'}]}).success,false);
assert.equal(dataSchema.safeParse({...d,tasks:[{...task,minutes:20}]}).success,false);
assert.equal(dataSchema.safeParse({...d,expenses:[{id:'e',projectId:'',merchant:'x',date:'2026-10-04',total:-2,tax:0,fileId:'',fileName:'',submitted:false,invoiceId:''}]}).success,false);
console.log('PASS: data validation, quarter-hour blocks, interval conflicts, rollover/deadlines, recurrence, invoice rounding, note arithmetic and conversions.');
